import { webkit } from 'playwright';
const browser=await webkit.launch({headless:false});
const page=await browser.newPage({viewport:{width:1800,height:950}});
await page.goto(process.env.EARTHLINE_URL||'http://127.0.0.1:8787/',{waitUntil:'domcontentloaded',timeout:90000});
await page.waitForSelector('#searchInput',{timeout:30000});
await page.evaluate(()=>{const i=document.getElementById('searchInput'),b=document.getElementById('runBtn');i.value='Vermont';i.dispatchEvent(new Event('input',{bubbles:true}));i.dispatchEvent(new Event('change',{bubbles:true}));b.click();});
await page.waitForFunction(()=>!!window.EARTHLINE_REGIONAL_PERFORMANCE_16191||!!window.EARTHLINE_LAST_LIVE_REGIONAL_ERROR_15970,{timeout:90000,polling:100});
await page.waitForTimeout(300);
const out=await page.evaluate(()=>({perf:window.EARTHLINE_REGIONAL_PERFORMANCE_16191||null,phases:window.EARTHLINE_MAKESWALES_POSTSKIP_17314||[],publication:window.EARTHLINE_PUBLICATION_CLIP_PHASE_17314||null,supertile:window.EARTHLINE_STATEWIDE_SUPERTILE_16839||null,error:window.EARTHLINE_LAST_LIVE_REGIONAL_ERROR_15970||null}));
console.log('EARTHLINE_POSTSKIP_VERMONT_17372 '+JSON.stringify(out));
await browser.close();
